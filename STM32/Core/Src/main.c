void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) {
  if (htim->Instance == TIM2) {
    UTIL_SEQ_SetTask(1U << CFG_TASK_ADC_ID, CFG_SEQ_PRIO_0);
    if (++bleDivider >= 2) {
      bleDivider = 0;

      UTIL_SEQ_SetTask(1U << CFG_TASK_BLE_WEIGHT_ID, CFG_SEQ_PRIO_0);
    }
  }
}
